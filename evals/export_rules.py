"""Export the parts of the checker that are DATA, so a second implementation cannot drift.

`assertions.py` is the source of truth, and it is Python. The desktop app's copy checker is
TypeScript (see ../DESKTOP_APP_BRIEF.md), so every rule expressed as a word list or a
pattern currently exists twice, in two languages, kept in sync by memory. It was not: the
interjections, the repeated-letter rule and the CTA one-action rule landed here and never
reached the app, and the app went on showing PASS for "Oooh" and "Cancel or die".

This writes rules.json from the live Python objects. The app reads that file instead of
holding its own copy of the lists. What genuinely cannot be data (the surface-aware
ampersand rule, the case scan, the money format) stays as code in both places, and is
listed under "code_only" so the port knows exactly what it still owes.

    python export_rules.py           write rules.json
    python export_rules.py --check   fail if rules.json is stale (a gate)
"""
import io
import json
import os
import sys

import assertions

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rules.json")


def build():
    return {
        "_": "Generated by export_rules.py from assertions.py. Do not edit by hand.",
        "version": 1,
        "checks": sorted(assertions.REGISTRY),
        "universal": assertions.UNIVERSAL,
        "surfaces": {k: v for k, v in sorted(assertions.SURFACE_CHECKS.items())},
        "lists": {
            "banned_terms": assertions.BANNED_TERMS,
            "prohibited_claims": assertions.PROHIBITED_CLAIMS,
            "not_inclusive": assertions.NOT_INCLUSIVE,
            "must_expand": assertions.MUST_EXPAND,
            "generic_cta": sorted(assertions.GENERIC_CTA),
            "generic_errors": sorted(assertions.GENERIC_ERRORS),
            "generic_required": assertions.GENERIC_REQUIRED,
            "title_case_ok": sorted(assertions.TITLE_CASE_OK),
            "proper_nouns": assertions.PROPER_NOUNS,
            "ampersand_ok_surfaces": sorted(assertions.AMPERSAND_OK),
        },
        "patterns": {
            "_": "JavaScript-compatible source strings. Match case-insensitively unless noted.",
            "banned_term_template": "\\b{term}s?\\b",
            "repeated_chars": "([A-Za-z\\u00c0-\\u017f])\\1{2,}",
            "repeated_chars_exempt": "^(?:#[0-9A-Fa-f]{3,8}|(?:https?://|www\\.)\\S+|[A-Z0-9/#_-]+)$",
            "cta_two_actions": "\\b(?:or|and|then)\\b",
            "emoji": "[\\u{1F300}-\\u{1FAFF}\\u{2600}-\\u{27BF}\\u{1F1E6}-\\u{1F1FF}]",
        },
        "cta": {"max_words": 3, "no_punctuation": ".,:;!?", "no_digits": True},
        "code_only": [
            "A-EURO-FORMAT: the money grammar (dot thousands, comma decimals, no ',00', exactly two decimals with cents)",
            "A-CASE: the Title Case scan, with its six exemptions",
            "A-NO-BANNED: the surface-aware ampersand rule and login-as-a-verb",
            "A-FIELD-ERROR, A-TOAST, A-PUSH-*, and the other surface shapes",
        ],
    }


def main():
    fresh = json.dumps(build(), ensure_ascii=False, indent=2, sort_keys=False) + "\n"
    if "--check" in sys.argv:
        if not os.path.exists(OUT):
            print("rules.json is missing. Run: python export_rules.py")
            return 1
        if io.open(OUT, encoding="utf-8").read() != fresh:
            print("rules.json is STALE: assertions.py changed and the export did not.")
            print("A second implementation is reading this file. Run: python export_rules.py")
            return 1
        print("rules.json is current (%d checks, %d banned terms)."
              % (len(assertions.REGISTRY), len(assertions.BANNED_TERMS)))
        return 0
    io.open(OUT, "w", encoding="utf-8").write(fresh)
    print("wrote %s" % os.path.basename(OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
